    const key = el.dataset.i18nPlaceholder;
    if (UIStrings[currentLang] && UIStrings[currentLang][key]) el.placeholder = UIStrings[currentLang][key];
    else if (UIStrings.en[key]) el.placeholder = UIStrings.en[key];
